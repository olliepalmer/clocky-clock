// Builds glyphs.js: the outlines of "0123456789:" for every font in the clock.
//
//   node tools/extract-glyphs.mjs <dir-of-ttf-files> > glyphs.js
//
// Files are named like "Fira_Code.ttf" (the Google Fonts family name, spaces as underscores).
// Every glyph is normalised so that all fonts line up and morph cleanly:
//   * units are thousandths of that font's digit height (tallest digit - lowest digit)
//   * y points DOWN (canvas style) and 0 is the vertical middle of the digits
//   * x = 0 is the middle of the glyph's own ink
// Each contour is a flat list: x0, (y0*2 + onCurve0), x1, (y1*2 + onCurve1), ...
// (TrueType quadratic points; "on curve" flag in the low bit.)

import fs from 'node:fs';
import path from 'node:path';
import { loadFont } from './ttf.mjs';

const CHARS = '0123456789:';
const DIGITS = '0123456789';
const dir = process.argv[2];

function sampleBounds(contours) {
  let x0 = 1e9, x1 = -1e9, y0 = 1e9, y1 = -1e9;
  const add = (x, y) => { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); };
  for (const pts of contours) {
    const n = pts.length;
    if (!n) continue;
    // walk the TrueType contour (implied on-curve midpoints) and sample every quadratic
    const P = [];
    for (let i = 0; i < n; i++) {
      const a = pts[i], b = pts[(i + 1) % n];
      P.push(a);
      if (!a.on && !b.on) P.push({ x: (a.x + b.x) / 2, y: (a.y + b.y) / 2, on: true });
    }
    let s = P.findIndex((p) => p.on);
    if (s < 0) { P.unshift({ x: (P[0].x + P[P.length - 1].x) / 2, y: (P[0].y + P[P.length - 1].y) / 2, on: true }); s = 0; }
    const m = P.length;
    let i = 0;
    while (i < m) {
      const a = P[(s + i) % m], b = P[(s + i + 1) % m];
      add(a.x, a.y);
      if (!b.on) {
        const c = P[(s + i + 2) % m];
        for (let t = 1; t < 8; t++) {
          const u = t / 8, v = 1 - u;
          add(v * v * a.x + 2 * v * u * b.x + u * u * c.x, v * v * a.y + 2 * v * u * b.y + u * u * c.y);
        }
        i += 2;
      } else i += 1;
    }
  }
  return { x0, x1, y0, y1 };
}

const out = {};
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.ttf')).sort()) {
  const name = file.replace(/\.ttf$/, '').replace(/_/g, ' ');
  const font = loadFont(path.join(dir, file));
  const raw = {};
  for (const ch of CHARS) raw[ch] = font.contours(font.glyphFor(ch));

  // digit-height reference from all ten digits
  let top = -1e9, bot = 1e9;
  for (const ch of DIGITS) {
    const b = sampleBounds(raw[ch]);
    top = Math.max(top, b.y1);
    bot = Math.min(bot, b.y0);
  }
  const dh = top - bot, cy = (top + bot) / 2;
  const k = 1000 / dh;

  const g = {};
  for (const ch of CHARS) {
    const b = sampleBounds(raw[ch]);
    const cx = (b.x0 + b.x1) / 2;
    g[ch] = [
      Math.round((b.x1 - b.x0) * k),
      raw[ch].map((pts) => {
        const flat = [];
        for (const p of pts) flat.push(Math.round((p.x - cx) * k), Math.round(-(p.y - cy) * k) * 2 + (p.on ? 1 : 0));
        return flat;
      }),
    ];
  }
  out[name] = g;
}

process.stdout.write('// generated by tools/extract-glyphs.mjs -- do not edit\nwindow.GLYPHS = ' + JSON.stringify(out) + ';\n');
